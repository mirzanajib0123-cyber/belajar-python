# kegiatan 1 - eksplorasi for loop dan range()
# percobaan A
for i in range(6):
    print(i, end=" ")
    # output: 0 1 2 3 4 5 

# percoban B
for i in range(3, 9):
    print(i, end=" ")
    # output: 3 4 5 6 7 8 
print()
# percobaan C
for i in range(0, 21, 5):
    print(i, end=" ")
    # output: 0 5 10 15 20 
print()
# percoban D
for i in range(10, 0, -2):
    print(i, end=" ")
    # output: 10 8 6 4 2